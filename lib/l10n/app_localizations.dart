  /// Substitutes `{key}` placeholders in a translation string.
  /// e.g. `loc.format('sosAutoSendIn', {'n': '5'})`
  String format(String key, Map<String, String> params) {
    String val = get(key);
    params.forEach((k, v) => val = val.replaceAll('{$k}', v));
    return val;
  }

